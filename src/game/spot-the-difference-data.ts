import { asset } from "@/lib/asset";

export type DiffType =
  | "bird" | "butterfly" | "crab" | "starfish" | "fish"
  | "flower" | "cloud" | "snowflake" | "penguin" | "balloon"
  | "cat" | "ladybug" | "music-note" | "seashell" | "coconut" | "leaf";

// Three handpicked positions per item — one is chosen randomly each playthrough
export type DiffItem = {
  id: string;
  type: DiffType;
  positions: [[number, number], [number, number], [number, number]];
  color: string;
  label: string;
  scale?: number;
};

// Resolved version used during gameplay
export type ResolvedDiff = {
  id: string;
  type: DiffType;
  cx: number;
  cy: number;
  color: string;
  label: string;
  scale?: number;
};

export type Level = {
  page: number;
  country: string;
  music: string | null;
  rookieDiffs: DiffItem[];
  masterDiffs: DiffItem[];
};

export function resolveLevel(diffs: DiffItem[]): ResolvedDiff[] {
  return diffs.map((d) => {
    const [cx, cy] = d.positions[Math.floor(Math.random() * 3)];
    return { id: d.id, type: d.type, cx, cy, color: d.color, label: d.label, scale: d.scale };
  });
}

